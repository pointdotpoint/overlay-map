"""Emit r6/scripts/NightMap/Generated/TileManifest.reds."""
from __future__ import annotations


def _f(v: float) -> str:
    return f"{float(v):.1f}"


def _switch(name: str, ret: str, values: list[str], default: str) -> str:
    cases = "".join(f"            case {i}: return {v};\n" for i, v in enumerate(values))
    return (f"    public static func {name}(i: Int32) -> {ret} {{\n        switch i {{\n{cases}"
            f"            default: return {default};\n        }}\n    }}\n\n")


def _scalar(name: str, ret: str, value: str) -> str:
    return f"    public static func {name}() -> {ret} {{\n        return {value};\n    }}\n\n"


MAX_LITERAL = 128


def _chunks(idx: list[int]) -> list[list[int]]:
    return [idx[i:i + MAX_LITERAL] for i in range(0, len(idx), MAX_LITERAL)]


def _array_case(i: int, idx: list, typ: str = "Int32", fmt=str) -> str:
    """Case body building array<typ>; no literal exceeds MAX_LITERAL elements."""
    ch = _chunks(idx)
    if len(ch) == 1:
        return f"            case {i}: return [{', '.join(map(fmt, ch[0]))}];\n"
    pad = "                "
    body = f"            case {i}:\n{pad}let a: array<{typ}> = [{', '.join(map(fmt, ch[0]))}];\n"
    for n, c in enumerate(ch[1:], 1):
        body += (f"{pad}let c{n}: array<{typ}> = [{', '.join(map(fmt, c))}];\n"
                 f"{pad}for x in c{n} {{ ArrayPush(a, x); }}\n")
    return body + f"{pad}return a;\n"


def _array_func(name: str, typ: str, per_level: list[list], fmt=str) -> str:
    """Public dispatcher + per-level concat functions + <=MAX_LITERAL chunk functions (small bytecode per function)."""
    helpers, cases = "", ""
    for i, vals in enumerate(per_level):
        if not vals:
            continue
        ch = _chunks(vals)
        cases += f"            case {i}: return NMVectorManifest.{name}_L{i}();\n"
        if len(ch) == 1:
            helpers += (f"    private static func {name}_L{i}() -> array<{typ}> {{\n"
                        f"        return [{', '.join(map(fmt, ch[0]))}];\n    }}\n\n")
            continue
        body = f"        let a: array<{typ}>;\n"
        for n, c in enumerate(ch):
            helpers += (f"    private static func {name}_{i}_{n}() -> array<{typ}> {{\n"
                        f"        return [{', '.join(map(fmt, c))}];\n    }}\n\n")
            body += f"        let c{n}: array<{typ}> = NMVectorManifest.{name}_{i}_{n}();\n        for x in c{n} {{ ArrayPush(a, x); }}\n"
        helpers += f"    private static func {name}_L{i}() -> array<{typ}> {{\n{body}        return a;\n    }}\n\n"
    return (helpers + f"    public static func {name}(i: Int32) -> array<{typ}> {{\n        switch i {{\n{cases}"
            f"            default: break;\n        }}\n        let empty: array<{typ}>;\n        return empty;\n    }}\n\n")


def emit_manifest(levels: list[dict], world: tuple[float, float, float, float], game_version: str) -> str:
    out = ["// GENERATED by tools/tiles (nmtiles.manifest) - do not edit.\nmodule NightMap\n\n",
           "public abstract class NMTileManifest {\n"]
    out.append(_scalar("Available", "Bool", "true"))
    out.append(_scalar("SourceGameVersion", "String", f'"{game_version}"'))
    out.append(_scalar("LevelCount", "Int32", str(len(levels))))
    out.append(_switch("LevelMpp", "Float", [_f(l["mpp"]) for l in levels], "0.0"))
    out.append(_switch("LevelOriginX", "Float", [_f(l["origin_x"]) for l in levels], "0.0"))
    out.append(_switch("LevelOriginTop", "Float", [_f(l["origin_top"]) for l in levels], "0.0"))
    out.append(_switch("LevelNx", "Int32", [str(l["nx"]) for l in levels], "0"))
    out.append(_switch("LevelNy", "Int32", [str(l["ny"]) for l in levels], "0"))
    cases = ""
    for i, l in enumerate(levels):
        idx = sorted(iy * l["nx"] + ix for ix, iy in l["tiles"])
        if idx:
            cases += _array_case(i, idx)
    out.append("    public static func LevelTiles(i: Int32) -> array<Int32> {\n        switch i {\n" + cases +
               "            default: break;\n        }\n        let empty: array<Int32>;\n        return empty;\n    }\n\n")
    for name, v in zip(("WorldMinX", "WorldMinY", "WorldMaxX", "WorldMaxY"), world):
        out.append(_scalar(name, "Float", _f(v)))
    out.append("}\n")
    return "".join(out)


def emit_stub() -> str:
    src = emit_manifest([], (-8000.0, -8000.0, 8000.0, 8000.0), "none")
    return src.replace("public static func Available() -> Bool {\n        return true;",
                       "public static func Available() -> Bool {\n        return false;")


def _f3(v: float) -> str:
    return f"{float(v):.3f}"


VECTOR_STYLE_COUNT = 7


def emit_vector_manifest(levels: list[dict], game_version: str) -> str:
    out = ["// GENERATED by tools/tiles (nmtiles.manifest) - do not edit.\nmodule NightMap\n\n",
           "public abstract class NMVectorManifest {\n"]
    out.append(_scalar("Available", "Bool", "true" if levels else "false"))
    out.append(_scalar("SourceGameVersion", "String", f'"{game_version}"'))
    out.append(_scalar("LevelCount", "Int32", str(len(levels))))
    out.append(_scalar("StyleCount", "Int32", str(VECTOR_STYLE_COUNT)))
    for name, key in (("LevelMinMpp", "min_mpp"), ("LevelMaxMpp", "max_mpp"), ("LevelUnit", "unit"),
                      ("LevelCell", "cell"), ("LevelOriginX", "ox"), ("LevelOriginTop", "otop")):
        out.append(_switch(name, "Float", [_f3(l[key]) for l in levels], "0.0"))
    out.append(_switch("LevelNx", "Int32", [str(l["nx"]) for l in levels], "0"))
    out.append(_switch("LevelNy", "Int32", [str(l["ny"]) for l in levels], "0"))
    out.append(_array_func("LevelCells", "Int32", [[c["key"] for c in l["cells"]] for l in levels]))
    out.append(_array_func("LevelBounds", "Float", [[v for c in l["cells"] for v in c["bounds"]] for l in levels], _f3))
    out.append(_array_func("LevelCounts", "Int32", [[v for c in l["cells"] for v in c["counts"]] for l in levels]))
    out.append(_array_func("LevelPoints", "Int32", [[v for c in l["cells"] for v in c["points"]] for l in levels]))
    out.append("}\n")
    return "".join(out)


def emit_vector_stub() -> str:
    return emit_vector_manifest([], "none")
