"""Staged, immutable builds (.soak/builds/<id>/, laid out like the game folder). The sources are never touched."""
from __future__ import annotations

import json
import os
import re
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

if __package__:
    from .paths import PARTS, Paths, rels, tree_hash
else:     # run as a script by tools/check.sh --soak
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from soak.paths import PARTS, Paths, rels, tree_hash

BOOTSTRAP_REL = "r6/scripts/SoakBootstrap"
SCRIPTS_REL = "r6/scripts/NightMap"
SYSTEM = "Core/NightMapSystem.reds"
RENDERER = "Render/ItemRenderer.reds"
# Spliced into classes, with their private fields in reach: redscript's annotations can't target classes defined in
# scripts. (file under the scripts folder, class, file under tools/soak/autopilot)
BODIES = [(SYSTEM, "NightMapSystem", "SystemBody.inc"), (RENDERER, "NMItemRenderer", "RendererBody.inc")]
# Calls added at one exact place. (file, text, replacement)
PATCHES = [
    (SYSTEM, "    private func UpdateModules(dt: Float) {\n",
     "    private func UpdateModules(dt: Float) {\n        this.Soak_Frame(dt);\n"),
    (RENDERER, "            ic.SetAtlasResource(this.icon.atlas);\n",
     "            ic.SetAtlasResource(this.icon.atlas);\n            this.soakIconLoads += 1;\n"
     "            this.soakLoadAt = p;\n"),
    (RENDERER, "                        this.miniIcon[mi].SetAtlasResource(this.api.catAtlas[g2]);\n",
     "                        this.miniIcon[mi].SetAtlasResource(this.api.catAtlas[g2]);\n"
     "                        this.soakIconLoads += 1;\n                        this.soakLoadAt = new Vector2(x, y);\n"),
]


class BuildError(RuntimeError):
    pass


@dataclass(frozen=True)
class Build:
    id: str
    dir: Path
    parts: list[str]


def splice_class_body(text: str, class_name: str, body: str) -> str:
    """`body` added at the end of a class: redscript's annotations can't target classes defined in scripts."""
    start = re.search(rf"^public class {class_name}\b", text, re.M)
    end = re.compile(r"^}\s*$", re.M).search(text, start.end()) if start else None
    if end is None:
        raise BuildError(f"class {class_name} not found")
    return text[:end.start()] + body + text[end.start():]


def apply_overlay(scripts: Path, autopilot: Path) -> None:
    """The hooks' class bodies and calls, into a staged copy of the scripts; the sources are never touched."""
    for name, old, new in PATCHES:
        f = scripts / name
        text = f.read_text(encoding="utf-8")
        if text.count(old) != 1:
            raise BuildError(f"{name}: expected one {old!r}, found {text.count(old)}")
        f.write_text(text.replace(old, new), encoding="utf-8")
    for name, cls, inc in BODIES:
        f = scripts / name
        f.write_text(splice_class_body(f.read_text(encoding="utf-8"), cls, (autopilot / inc).read_text(encoding="utf-8")),
                     encoding="utf-8")


def _source(paths: Paths, part: str, rel: str) -> Path:
    repo = paths.repo
    if part == "scripts":
        return repo / "r6/scripts/NightMap"
    if part == "archive":
        return repo / rel
    if part == "bootstrap":
        return repo / "tools/soak/bootstrap"
    if part == "autopilot":
        return repo / "tools/soak/autopilot/SoakHooks.reds"
    raise BuildError(f"unknown part {part}")


def stage_build(paths: Paths, parts: list[str]) -> Build:
    root = paths.soak / "builds"
    tmp = root / f"tmp-{os.getpid()}"
    shutil.rmtree(tmp, ignore_errors=True)
    parts = list(parts)
    if "autopilot" in parts:
        if "scripts" not in parts or "bootstrap" not in parts:
            raise BuildError("autopilot needs the scripts and bootstrap parts")
        parts = [x for x in parts if x != "autopilot"] + ["autopilot"]  # an overlay: after scripts
    for part in parts:
        for rel in PARTS[part]:
            src = _source(paths, part, rel)
            if not src.exists():
                shutil.rmtree(tmp, ignore_errors=True)
                raise BuildError(f"part {part}: {src} is missing")
            dst = tmp / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            if src.is_dir():
                shutil.copytree(src, dst, symlinks=True)
            else:
                shutil.copy2(src, dst)
    if "autopilot" in parts:
        apply_overlay(tmp / SCRIPTS_REL, paths.repo / "tools/soak/autopilot")
    build_id = tree_hash(tmp, rels(parts))[:16]
    if "bootstrap" in parts:
        (tmp / BOOTSTRAP_REL / "SoakBuild.reds").write_text(
            "module SoakBootstrap\n\n// Generated by tools/soak/builds.py.\n"
            f'public func Soak_BuildId() -> String = "{build_id}"\n', encoding="utf-8")
    final = root / build_id
    if final.exists():
        shutil.rmtree(tmp, ignore_errors=True)
    else:
        (tmp / "manifest.json").write_text(json.dumps({"id": build_id, "parts": parts}, indent=1))
        tmp.rename(final)
    return Build(build_id, final, parts)


if __name__ == "__main__":   # tools/check.sh --soak: the same overlay on its sandbox copy
    apply_overlay(Path(sys.argv[1]), Path(sys.argv[2]))
