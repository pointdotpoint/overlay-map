"""Staged, immutable builds (.soak/builds/<id>/, laid out like the game folder). The sources are never touched."""
from __future__ import annotations

import json
import os
import re
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

if __package__:
    from .paths import PARTS, Paths, rels, tree_hash
else:     # run as a script by tools/check.sh --soak
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from soak.paths import PARTS, Paths, rels, tree_hash

BOOTSTRAP_REL = "r6/scripts/SoakBootstrap"
SYSTEM_REL = "r6/scripts/NightMap/Core/NightMapSystem.reds"


class BuildError(RuntimeError):
    pass


@dataclass(frozen=True)
class Build:
    id: str
    dir: Path
    parts: list[str]


def splice_class_body(text: str, class_name: str, body: str) -> str:
    """`body` added at the end of a class: redscript's annotations can't target classes defined in scripts."""
    start = re.search(rf"^public class {class_name}\b", text, re.M)
    end = re.compile(r"^}\s*$", re.M).search(text, start.end()) if start else None
    if end is None:
        raise BuildError(f"class {class_name} not found")
    return text[:end.start()] + body + text[end.start():]


def _source(paths: Paths, part: str, rel: str) -> Path:
    repo = paths.repo
    if part == "scripts":
        return repo / "r6/scripts/NightMap"
    if part == "archive":
        return repo / rel
    if part == "bootstrap":
        return repo / "tools/soak/bootstrap"
    if part == "autopilot":
        return repo / "tools/soak/autopilot/SoakHooks.reds"
    raise BuildError(f"unknown part {part}")


def stage_build(paths: Paths, parts: list[str]) -> Build:
    root = paths.soak / "builds"
    tmp = root / f"tmp-{os.getpid()}"
    shutil.rmtree(tmp, ignore_errors=True)
    parts = list(parts)
    if "autopilot" in parts:
        if "scripts" not in parts or "bootstrap" not in parts:
            raise BuildError("autopilot needs the scripts and bootstrap parts")
        parts = [x for x in parts if x != "autopilot"] + ["autopilot"]  # an overlay: after scripts
    for part in parts:
        for rel in PARTS[part]:
            src = _source(paths, part, rel)
            if not src.exists():
                shutil.rmtree(tmp, ignore_errors=True)
                raise BuildError(f"part {part}: {src} is missing")
            dst = tmp / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            if src.is_dir():
                shutil.copytree(src, dst, symlinks=True)
            else:
                shutil.copy2(src, dst)
    if "autopilot" in parts:
        system = tmp / SYSTEM_REL
        body = (paths.repo / "tools/soak/autopilot/SystemBody.inc").read_text(encoding="utf-8")
        system.write_text(splice_class_body(system.read_text(encoding="utf-8"), "NightMapSystem", body), encoding="utf-8")
    build_id = tree_hash(tmp, rels(parts))[:16]
    if "bootstrap" in parts:
        (tmp / BOOTSTRAP_REL / "SoakBuild.reds").write_text(
            "module SoakBootstrap\n\n// Generated by tools/soak/builds.py.\n"
            f'public func Soak_BuildId() -> String = "{build_id}"\n', encoding="utf-8")
    final = root / build_id
    if final.exists():
        shutil.rmtree(tmp, ignore_errors=True)
    else:
        (tmp / "manifest.json").write_text(json.dumps({"id": build_id, "parts": parts}, indent=1))
        tmp.rename(final)
    return Build(build_id, final, parts)


if __name__ == "__main__":   # tools/check.sh --soak: splice the staged class the same way
    target = Path(sys.argv[1])
    target.write_text(splice_class_body(target.read_text(encoding="utf-8"), "NightMapSystem",
                                        Path(sys.argv[2]).read_text(encoding="utf-8")), encoding="utf-8")
