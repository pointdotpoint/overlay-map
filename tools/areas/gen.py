#!/usr/bin/env python3
"""Merge the game's area outlines (scan.py) with custom_areas.json into OverlayMap's area data.

  gen.py [--outlines ~/.cache/nightmap-sectors/areas/outlines.json] [--custom tools/areas/custom_areas.json]
         [--out r6/scripts/OverlayMap/Generated/AreaData.reds] [--preview PNG]
Areas are emitted smallest first, so the runtime takes the first hit. Game areas carry only their Districts.* key;
the game names them (localized) at runtime. Prints the counts and every overlapping pair above 0.05 km2.
"""
from __future__ import annotations

import argparse
import json
import re
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "r6/scripts/OverlayMap/Generated/AreaData.reds"
OUTLINES = Path.home() / ".cache/nightmap-sectors/areas/outlines.json"
CUSTOM = HERE / "custom_areas.json"
TILES = ROOT / "tools/tiles/build/png"
CHUNK = 8000
DROP = re.compile(r"(?i)cyberspace|VR_Tutorial|SpaceStation")
DROP_TOWER = re.compile(r"^Districts\.ArasakaTower(?!Lobby$)")
BAD = re.compile(r'[|;"]')


def polygon_area(poly) -> float:
    a = 0.0
    for k in range(len(poly)):
        (x1, y1), (x2, y2) = poly[k], poly[(k + 1) % len(poly)]
        a += x1 * y2 - x2 * y1
    return abs(a) / 2


@dataclass
class Area:
    key: str
    name: str
    parent: str
    desc: str
    poly: list[tuple[float, float]]

    @property
    def size(self) -> float:
        return polygon_area(self.poly)


def keep_id(id_: str) -> bool:
    return id_ not in ("", "0") and not DROP.search(id_) and not DROP_TOWER.search(id_)


def game_areas(rows: list[dict]) -> list[Area]:
    """Drop unwanted IDs; where an ID has outlines named *_new, keep only those (they supersede the old shapes)."""
    rows = [r for r in rows if keep_id(r["id"]) and len(r["poly"]) >= 3]
    is_new = lambda r: r["debug"].strip("{}").endswith("_new")  # noqa: E731
    renewed = {r["id"] for r in rows if is_new(r)}
    return [Area(r["id"], "", "", "", [tuple(p) for p in r["poly"]]) for r in rows
            if r["id"] not in renewed or is_new(r)]


def load_custom(path: Path) -> list[Area]:
    return [Area(c["key"], c["name"], c.get("parent", ""), c.get("desc", ""), [tuple(p) for p in c["poly"]])
            for c in json.loads(path.read_text())]


def merge(game: list[Area], custom: list[Area]) -> list[Area]:
    return sorted(game + custom, key=lambda a: a.size)   # stable: ties keep the generated order


def _num(v: float) -> str:
    s = f"{v:.1f}"
    return "0.0" if s == "-0.0" else s


EMPTY = "~"   # the game's StrSplit may drop empty fields, so an empty field is written as this


def entry(a: Area) -> str:
    for f in (a.key, a.name, a.parent, a.desc):
        if BAD.search(f) or f == EMPTY:
            raise ValueError(f"area {a.key!r}: field {f!r} contains | ; or \" (or is {EMPTY!r})")
    if not a.key:
        raise ValueError("area without a key")
    fields = [f or EMPTY for f in (a.name, a.parent, a.desc)]
    return "|".join((a.key, *fields, ",".join(f"{_num(x)},{_num(y)}" for x, y in a.poly)))


def emit(areas: list[Area]) -> str:
    chunks: list[list[str]] = [[]]
    size = 0
    for e in map(entry, areas):
        if len(e) > CHUNK:
            raise ValueError(f"entry longer than {CHUNK} characters: {e[:40]}...")
        if chunks[-1] and size + 1 + len(e) > CHUNK:
            chunks.append([])
            size = 0
        size += len(e) + (1 if chunks[-1] else 0)
        chunks[-1].append(e)
    if not chunks[-1]:
        chunks.pop()
    lines = ["module OverlayMap", "",
             "// Generated by tools/areas/gen.py from the game's world sectors and tools/areas/custom_areas.json."
             " Do not edit.",
             "// An entry is key|name|parent|desc|x1,y1,x2,y2,...; entries are joined by ';', smallest area first.",
             "// An empty name, parent or desc is written as '~' (the game's StrSplit may drop empty fields).",
             "// Game areas have an empty name and parent: the runtime names them from the Districts.* record.",
             "public abstract class NMAreaData {",
             f"    public static func Count() -> Int32 {{ return {len(areas)}; }}",
             f"    public static func Chunks() -> Int32 {{ return {len(chunks)}; }}", "",
             "    public static func Chunk(index: Int32) -> String {", "        switch index {"]
    for k, c in enumerate(chunks):
        lines.append(f"            case {k}: return \"{';'.join(c)}\";")
    lines += ["        }", "        return \"\";", "    }", "}", ""]
    return "\n".join(lines)


def contains(poly, x: float, y: float) -> bool:
    inside = False
    j = len(poly) - 1
    for i in range(len(poly)):
        (xi, yi), (xj, yj) = poly[i], poly[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            inside = not inside
        j = i
    return inside


def overlaps(areas: list[Area], step: float = 40.0, min_km2: float = 0.05) -> list[tuple[str, str, float]]:
    """Pairs of different keys whose overlap, sampled on a step-metre grid, is above min_km2."""
    boxes = [(min(x for x, _ in a.poly), min(y for _, y in a.poly), max(x for x, _ in a.poly),
              max(y for _, y in a.poly)) for a in areas]
    x0, y0 = min(b[0] for b in boxes), min(b[1] for b in boxes)
    x1, y1 = max(b[2] for b in boxes), max(b[3] for b in boxes)
    cells: dict[tuple[str, str], int] = {}
    y = y0 + step / 2
    while y < y1:
        row = [k for k, b in enumerate(boxes) if b[1] <= y <= b[3]]
        x = x0 + step / 2
        while x < x1:
            keys = sorted({areas[k].key for k in row if boxes[k][0] <= x <= boxes[k][2] and contains(areas[k].poly, x, y)})
            for i in range(len(keys)):
                for j in range(i + 1, len(keys)):
                    cells[(keys[i], keys[j])] = cells.get((keys[i], keys[j]), 0) + 1
            x += step
        y += step
    return sorted(((a, b, n * step * step / 1e6) for (a, b), n in cells.items() if n * step * step / 1e6 > min_km2),
                  key=lambda t: -t[2])


def preview(areas: list[Area], out: Path) -> None:
    """Every outline over the L4 tiles (8 m/px, origin x -8192, top 8192, 512 px tiles)."""
    from PIL import Image, ImageDraw

    mpp, ox, ot, t = 8.0, -8192.0, 8192.0, 512
    mos = Image.new("RGB", (4 * t, 4 * t), (8, 18, 26))
    for layer, tint in (("bfill", (40, 70, 90)), ("road", (60, 140, 200))):
        for a in range(4):
            for b in range(4):
                p = TILES / f"{layer}_L4_t_{a}_{b}.png"
                if p.exists():
                    im = Image.open(p).convert("RGBA")
                    mos.paste(Image.new("RGB", im.size, tint), (a * t, b * t), im.getchannel("A"))
    d = ImageDraw.Draw(mos)
    pal = [(255, 90, 90), (255, 220, 60), (120, 255, 120), (255, 130, 255), (255, 170, 60), (90, 255, 240)]
    for i, a in enumerate(sorted(areas, key=lambda a: a.key)):
        pts = [((x - ox) / mpp, (ot - y) / mpp) for x, y in a.poly]
        c = (255, 255, 255) if a.name else pal[i % len(pal)]
        d.line(pts + [pts[0]], fill=c, width=3 if a.name else 2)
        cx, cy = sum(p[0] for p in pts) / len(pts), sum(p[1] for p in pts) / len(pts)
        d.text((cx - 20, cy), a.key.replace("Districts.", ""), fill=c)
    mos.save(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--outlines", type=Path, default=OUTLINES)
    ap.add_argument("--custom", type=Path, default=CUSTOM)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--preview", type=Path)
    args = ap.parse_args(argv)
    custom = load_custom(args.custom)
    areas = merge(game_areas(json.loads(args.outlines.read_text())), custom)
    args.out.write_text(emit(areas))
    print(f"{len(areas)} areas ({len(custom)} custom, {len({a.key for a in areas})} keys) -> {args.out}")
    for a, b, km2 in overlaps(areas):
        print(f"overlap {a} / {b}: {km2:.2f} km2")
    if args.preview:
        preview(areas, args.preview)
        print(f"preview -> {args.preview}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
